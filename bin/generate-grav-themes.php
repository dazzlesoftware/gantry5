<?php

/**
 * Generate the Grav platform adapter for every Gantry theme that does not
 * already provide one. Theme-specific configuration is taken from WordPress
 * first, then Joomla; shared assets continue to live in ../common.
 *
 * Usage: php bin/generate-grav-themes.php [--check]
 */

declare(strict_types=1);

$root = dirname(__DIR__);
$check = in_array('--check', $argv, true);
$themesRoot = $root . '/themes';
$generated = [];
$outdated = [];

foreach (new DirectoryIterator($themesRoot) as $themeDirectory) {
    if (!$themeDirectory->isDir() || $themeDirectory->isDot()) {
        continue;
    }

    $slug = $themeDirectory->getFilename();
    $path = $themeDirectory->getPathname();
    $grav = $path . '/grav';

    $marker = $grav . '/.generated-grav-theme';
    $generatedBlueprint = $grav . '/blueprints.yaml';
    $isGenerated = is_file($marker)
        || (is_file($generatedBlueprint) && str_contains(file_get_contents($generatedBlueprint), ' theme for Gantry 5.'));

    // Existing hand-maintained Grav themes must never be replaced.
    if ((is_dir($grav) && !$isGenerated) || !is_dir($path . '/common')) {
        continue;
    }

    $sourcePlatform = is_file($path . '/wordpress/gantry/theme.yaml') ? 'wordpress' : 'joomla';
    $source = $path . '/' . $sourcePlatform;
    $sourceYaml = $source . '/gantry/theme.yaml';
    if (!is_file($sourceYaml)) {
        continue;
    }

    $sourceConfig = file_get_contents($sourceYaml);
    preg_match('/^\s{2}name:\s*[\'\"]?([^\'\"\r\n]+)[\'\"]?/m', $sourceConfig, $nameMatch);
    $name = trim($nameMatch[1] ?? ucwords(str_replace(['-', '_'], ' ', $slug)));
    $class = 'G5_' . str_replace(' ', '_', ucwords(str_replace(['-', '_'], ' ', $slug)));
    $config = gravThemeYaml($sourceConfig, $slug, $sourcePlatform);

    $files = [
        '.generated-grav-theme' => "Generated by bin/generate-grav-themes.php; do not edit platform files by hand.\n",
        'blueprints.yaml' => blueprint($name),
        'g5_' . $slug . '.yaml' => "enabled: true\n",
        'theme.php' => gravThemePhp($class),
        'includes/theme.php' => gantryThemePhp($class),
        'gantry/theme.yaml' => $config,
        'scss/' . $slug . '-grav.scss' => gravScss($slug),
        'scss/' . $slug . '-grav/_core.scss' => gravCoreScss(),
    ];

    foreach ($files as $relative => $contents) {
        $destination = $grav . '/' . $relative;
        if (!is_file($destination) || file_get_contents($destination) !== $contents) {
            $outdated[] = $slug . '/grav/' . $relative;
            if (!$check) {
                $directory = dirname($destination);
                if (!is_dir($directory)) {
                    mkdir($directory, 0777, true);
                }
                file_put_contents($destination, $contents);
            }
        }
    }

    foreach (['screenshot.png', 'thumbnail.png'] as $image) {
        $destination = $grav . '/' . $image;
        $sourceImage = $source . '/screenshot.png';
        if (!is_file($sourceImage)) {
            $sourceImage = $source . '/template_preview.png';
        }
        if (is_file($sourceImage) && (!is_file($destination) || hash_file('sha256', $destination) !== hash_file('sha256', $sourceImage))) {
            $outdated[] = $slug . '/grav/' . $image;
            if (!$check) {
                copy($sourceImage, $destination);
            }
        }
    }

    $generated[] = $slug;
}

if ($check && $outdated) {
    fwrite(STDERR, "Grav theme adapters are out of date:\n - " . implode("\n - ", $outdated) . "\n");
    exit(1);
}

echo $check
    ? sprintf("All %d generated Grav theme adapters are current.\n", count($generated))
    : sprintf("Generated %d Grav theme adapters: %s\n", count($generated), implode(', ', $generated));

function blueprint(string $name): string
{
    return <<<YAML
name: {$name}
version: "@version@"
description: "{$name} theme for Gantry 5."
icon: gantry
author:
  name: Dazzle Software
  email: 'support@dazzlesoftware.org'
  url: 'https://dazzlesoftware.org'
homepage: 'https://dazzlesoftware.org'
readme: 'https://github.com/gantry/gantry5/blob/master/README.md'
keywords: gantry, gantry5, theme
bugs: 'https://github.com/gantry/gantry5/issues'
license: GPL-3.0-or-later

dependencies:
  - { name: grav, version: '>=1.7' }
  - { name: gantry5, version: '>=5.5' }

form:
  validation: loose
  fields:

YAML;
}

function gravThemeYaml(string $yaml, string $slug, string $sourcePlatform): string
{
    $yaml = preg_replace('/^(\s{2}version:)\s*.*$/m', '$1 \'@version@\'', $yaml, 1);
    $yaml = preg_replace('/^(\s{2}date:)\s*.*$/m', '$1 \'@versiondate@\'', $yaml, 1);
    $yaml = preg_replace('/^(\s{4}platform:)\s*.*$/m', '$1 grav', $yaml, 1);
    $yaml = preg_replace('/^(\s{4}parent:)\s*.*$/m', '$1 g5_' . $slug, $yaml, 1);
    $yaml = preg_replace('/^(\s{4}base:)\s*.*$/m', '$1 gantry-theme://common', $yaml, 1);
    $yaml = preg_replace('/^(\s{4}file:)\s*.*$/m', '$1 \'gantry-theme://includes/theme.php\'', $yaml, 1);
    $yaml = preg_replace('/^(\s{4}class:)\s*.*$/m', '$1 \'\\Gantry\\Framework\\Theme\'', $yaml, 1);
    $yaml = preg_replace('/^\s{4}textdomain:.*\R/m', '', $yaml);
    $yaml = preg_replace('/^(\s{4}gantry:)\s*.*$/m', '$1 \'5.5\'', $yaml);
    $yaml = str_replace($slug . '-' . $sourcePlatform, $slug . '-grav', $yaml);
    $yaml = preg_replace('/\Rchrome:\R[\s\S]*$/', "\n", $yaml);

    // Keep the platform stylesheet compiled with the base stylesheet, matching Helium.
    $persistent = "/(\n    persistent:\R(?:      - .*\R)+)/";
    if (preg_match($persistent, $yaml, $match) && !str_contains($match[1], $slug . '-grav')) {
        $replacement = rtrim($match[1]) . "\n      - {$slug}-grav\n";
        $yaml = preg_replace($persistent, $replacement, $yaml, 1);
    }

    $overrides = "/(\n    overrides:\R)((?:      - .*\R)+)/";
    if (preg_match($overrides, $yaml, $match)) {
        $items = preg_replace('/^      - ' . preg_quote($slug . '-grav', '/') . '\R/m', '', $match[2]);
        $yaml = preg_replace($overrides, '$1' . $items, $yaml, 1);
    }

    return rtrim($yaml) . "\n";
}

function gravThemePhp(string $class): string
{
    return str_replace('__CLASS__', $class, <<<'PHP'
<?php

/**
 * @package   Genesis
 * @author    Dazzle Software https://dazzlesoftware.org
 * @copyright Copyright (C) 2026 Dazzle Software, LLC
 * @license   GNU/GPLv3 and later
 */

namespace Grav\Theme;

use Gantry\Framework\Gantry;
use Gantry\Framework\Theme as GantryTheme;
use Grav\Common\Theme;
use DazzleSoftware\Toolbox\ResourceLocator\UniformResourceLocator;

class __CLASS__ extends Theme
{
    public $gantry = '5.5';
    protected $theme;

    public static function getSubscribedEvents()
    {
        return ['onThemeInitialized' => ['onThemeInitialized', 0]];
    }

    public function onThemeInitialized()
    {
        if (defined('GRAV_CLI') && GRAV_CLI) {
            return;
        }

        /** @var UniformResourceLocator $locator */
        $locator = $this->grav['locator'];
        $path = $locator('theme://');
        $name = $this->name;

        if (!class_exists('\Gantry5\Loader')) {
            if ($this->isAdmin()) {
                $this->grav['messages']->add('Please enable Gantry 5 plugin in order to use current theme!', 'error');
                return;
            }
            throw new \LogicException('Please install and enable Gantry 5 Framework plugin!');
        }

        \Gantry5\Loader::setup();
        $gantry = Gantry::instance();
        $gantry['theme.path'] = $path;
        $gantry['theme.name'] = $name;
        require $locator('theme://includes/theme.php');
        $gantry['theme'] = static function ($c) {
            return new \Gantry\Theme\__CLASS__($c['theme.path'], $c['theme.name']);
        };
    }
}

PHP
    );
}

function gantryThemePhp(string $class): string
{
    return str_replace('__CLASS__', $class, <<<'PHP'
<?php

namespace Gantry\Theme;

use Gantry\Framework\Theme;

class __CLASS__ extends Theme {}

PHP
    );
}

function gravScss(string $slug): string
{
    return <<<SCSS
// Grav platform styles for {$slug}.
\$output-bourbon-deprecation-warnings: false;
@import "vendor/bourbon/bourbon";

@import "configuration/nucleus/base";
@import "configuration/grav/base";
@import "configuration/base";

@import "grav";
@import "{$slug}-grav/core";

SCSS;
}

