{
    return <<<'SCSS'
#g-page-surround {
    #grav-login {
        .secondary-accent {
            @include breakpoint(mobile-only) {
                text-align: center;
            }

            .forgot & {
                text-align: center;
            }

            .button.primary,
            .button.secondary {
                margin-top: 10px;
                padding: 10px;
            }

            .rememberme {
                padding-top: 12px;

                @include breakpoint(mobile-only) {
                    display: block;
                    float: none;
                }
            }
        }
    }
}

SCSS;
}
