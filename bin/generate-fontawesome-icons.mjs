import fs from 'node:fs';
import path from 'node:path';

const argumentsMap = new Map();

for (let index = 2; index < process.argv.length; index += 2) {
    argumentsMap.set(process.argv[index], process.argv[index + 1]);
}

const metadataFile = argumentsMap.get('--metadata');
const version = argumentsMap.get('--version');
const outputFile = argumentsMap.get('--output') ?? path.resolve(
    'src/classes/Genesis/Admin/Controller/Json/Icons/FontAwesome7.php'
);

if (!metadataFile || !version) {
    console.error('Usage: node bin/generate-fontawesome-icons.mjs --metadata <icons.json> --version <version> [--output <file>]');
    process.exit(1);
}

const metadata = JSON.parse(fs.readFileSync(metadataFile, 'utf8'));
const prefixes = new Map([
    ['brands', 'fab'],
    ['regular', 'far'],
    ['solid', 'fas']
]);
const icons = new Set();

for (const [name, definition] of Object.entries(metadata)) {
    // The upstream repository metadata also describes Pro styles. Only use
    // styles explicitly included in the Font Awesome Free collection.
    for (const style of definition.free ?? []) {
        const prefix = prefixes.get(style);

        if (!prefix) {
            continue;
        }

        icons.add(`${prefix} fa-${name}`);

        for (const alias of definition.aliases?.names ?? []) {
            icons.add(`${prefix} fa-${alias}`);
        }
    }
}

const list = [...icons].sort((left, right) => left.localeCompare(right));
const entries = list.map((icon) => `    '${icon}',`).join('\n');
const output = `<?php

declare(strict_types=1);

if (!defined('ABSPATH')) {
    exit;
}

// Font Awesome Free ${version} icon list (${list.length} style/name combinations).
// Generated by bin/generate-fontawesome-icons.bat; do not edit manually.

return [
${entries}
];
`;

fs.mkdirSync(path.dirname(outputFile), { recursive: true });
fs.writeFileSync(outputFile, output, 'utf8');

console.log(`Generated ${list.length} icon entries in ${outputFile}`);
